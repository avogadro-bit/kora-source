def apply_reference_film(linear,film):
    if film=='classic_negative':
        from .classic_negative import refine_classic_negative
        return refine_classic_negative(apply_official(linear,film))
    a=apply_official(linear,'provia')
    coef=np.asarray(COEFFICIENTS[film],dtype=np.float32)
    output=np.empty_like(a)
    def process(start,stop):
        block=a[start:stop];r,g,b=np.moveaxis(block,-1,0);y=(r+g+b)/3
        features=(np.ones_like(r),r,g,b,r*g,r*b,g*b,r*r,g*g,b*b,
                  r*r*r,g*g*g,b*b*b,r*g*b,r*r*g,r*r*b,g*g*r,g*g*b,b*b*r,b*b*g)
        delta=np.zeros_like(block)
        for term,weights in zip(features,coef):delta+=term[...,None]*weights
        delta*=np.maximum(0,4*y*(1-y))[...,None]
        output[start:stop]=np.clip(block+np.clip(delta,-.15,.15),0,1)
    run_parallel_rows(len(a),process,block_rows=128)
    return output
